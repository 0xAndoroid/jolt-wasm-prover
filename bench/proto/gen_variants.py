"""Generates the unrolled V2-family kernels.

    uv run python bench/proto/gen_variants.py      # rewrites commit_accumulate.wgsl (= VARIANTS[BEST])

commit_proto.py --variant vN builds the other variants in memory via source(); they are not checked in.

Each variant: workgroup = (chunk of CHUNK positions, group of COLS columns, block); A2[q] staged in
workgroup memory as 32-bit limbs; every thread owns CPT coefficients (i, i + 512/CPT, ...) x COLS
columns, accumulated as 16-bit digits in 8 u32 (2 vec4) per (column, coefficient).
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

HEAD = """// {title}
// Generated by gen_variants.py — edit the generator, not this file.
// dispatch: (num_chunks, colcap/{cols}, blocks). Partials per chunk; reduce.wgsl sums chunks and canonicalizes.
override CHUNK: u32 = 128u;
const COLS: u32 = {cols}u;
const CPT: u32 = {cpt}u;                 // coefficients per thread
const WG: u32 = 512u / CPT;
@group(0) @binding(0) var<uniform> P: Params;
@group(0) @binding(1) var<storage, read> A2: array<vec4<u32>>;
@group(0) @binding(2) var<storage, read> HOT: array<u32>;   // code bytes, row stride = colcap bytes
@group(0) @binding(3) var<storage, read_write> PART: array<vec4<u32>>;
var<workgroup> S: array<vec4<u32>, 1024>;

@compute @workgroup_size(WG)
fn main(@builtin(local_invocation_id) lid: vec3<u32>, @builtin(workgroup_id) wid: vec3<u32>) {{
  let i = lid.x;
  let chunk = wid.x;
  let g = wid.y;
  let b = wid.z;
{acc_decl}
  let q0 = chunk * CHUNK;
  let row_u32 = P.colcap / 4u;
  for (var qq = 0u; qq < CHUNK; qq++) {{
    let q = q0 + qq;
    workgroupBarrier();
    for (var k = i; k < 1024u; k += WG) {{
      S[k] = A2[q * 1024u + k];
    }}
    workgroupBarrier();
    let row0 = (b * P.positions + q) * 32u;
    for (var r = 0u; r < 32u; r++) {{
      let hbase = (row0 + r) * row_u32 + (g * COLS) / 4u;
      let cshift0 = ((g * COLS) % 4u) * 8u;   // 0 unless COLS < 4
{words}
      let sbase = i - r * 16u;
{cols_code}
    }}
  }}
  let cbase = g * COLS;
{store}
}}
"""


SCHEMES = {
    # inner add for one staged coefficient x (vec4<u32>), and how the two accumulators map to PART digits
    "digits": dict(add="lo{a} += x & vec4<u32>(0xFFFFu); hi{a} += x >> vec4<u32>(16u);",
                   store="PART[o * 2u] = lo{a}; PART[o * 2u + 1u] = hi{a};"),
    # lo holds the wrapping full-limb sum, hi the high-half sum; low digits = lo - (hi << 16) (exact mod 2^32)
    "fullhi": dict(add="lo{a} += x; hi{a} += x >> vec4<u32>(16u);",
                   store="PART[o * 2u] = lo{a} - (hi{a} << vec4<u32>(16u)); PART[o * 2u + 1u] = hi{a};"),
    # lo = wrapping limb sum, hi = carry count per limb; PART mode 1 (reduce.wgsl handles (acc, carry) pairs)
    "lazycarry": dict(add="let t{a} = lo{a} + x; hi{a} += vec4<u32>(t{a} < x); lo{a} = t{a};",
                      store="PART[o * 2u] = lo{a}; PART[o * 2u + 1u] = hi{a};"),
}


def build(title, cols, cpt, scheme):
    sch = SCHEMES[scheme]
    step = 512 // cpt
    acc = []
    for c in range(cols):
        for t in range(cpt):
            acc.append(f"  var lo{c}_{t} = vec4<u32>(0u);\n  var hi{c}_{t} = vec4<u32>(0u);")
    words = "\n".join(f"      let w{k} = HOT[hbase + {k}u];" for k in range(max(1, cols // 4)))
    cols_code = []
    for c in range(cols):
        body = ["          let j0 = (sbase - code) & 1023u;"]
        for t in range(cpt):
            j = "j0" if t == 0 else f"((j0 + {t * step}u) & 1023u)"
            body.append("          { let x = S[" + j + "]; " + sch["add"].format(a=f"{c}_{t}") + " }")
        body = "\n".join(body)
        cols_code.append(f"""      {{
        let code = (w{c // 4} >> (cshift0 + {(c % 4) * 8}u)) & 0xFFu;
        if (code < 16u) {{
{body}
        }}
      }}""")
    store = []
    for c in range(cols):
        for t in range(cpt):
            store.append(f"  {{ let o = ((chunk * P.colcap + cbase + {c}u) * P.blocks + b) * 512u + i + {t * step}u; "
                         + sch["store"].format(a=f"{c}_{t}") + " }")
    return HEAD.format(title=title, cols=cols, cpt=cpt, acc_decl="\n".join(acc), words=words,
                       cols_code="\n".join(cols_code), store="\n".join(store))


VARIANTS = {
    # name: (cols per workgroup, coefficients per thread, scheme)
    "v2b": (8, 1, "digits"),
    "v3": (4, 1, "digits"),
    "v4": (8, 2, "digits"),
    "v5": (4, 2, "digits"),
    "v6": (4, 2, "fullhi"),
    "v7": (4, 2, "lazycarry"),
    "v8": (4, 4, "digits"),
    "v9": (2, 4, "digits"),
    "v10": (2, 2, "digits"),
    "v11": (2, 4, "fullhi"),
    "v12": (2, 8, "digits"),
    "v13": (1, 8, "digits"),
    "v14": (1, 4, "digits"),
}

BEST = "v9"


def source(name):
    cols, cpt, scheme = VARIANTS[name]
    label = f"CHOSEN KERNEL (= {BEST})" if name == BEST else name.upper()
    return build(f"{label}: {cols} columns x {cpt} coefficients per thread ({512 // cpt} threads), "
                 f"{cols * cpt * 8} accumulator words, scheme={scheme}.", cols, cpt, scheme)


if __name__ == "__main__":
    (HERE / "commit_accumulate.wgsl").write_text(source(BEST))
